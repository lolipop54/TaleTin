import 'dart:io';

import 'package:ffigen/ffigen.dart';

void main(List<String> args) {
  final root = Platform.script.resolve('../');
  final header = root.resolve('src/direct.h');
  FfiGenerator(
    headers: Headers(
      entryPoints: [header],
      include: (uri) => {header, root.resolve('src/extract.h')}.contains(uri),
    ),
    functions: Functions(
      include: (decl) => decl.originalName.startsWith('gt_mobi_'),
    ),
    output: Output(
      dartFile: root.resolve('lib/src/third_party/extract.g.dart'),
      style: const NativeExternalBindings(
        assetId: 'package:mobi_native/mobi_native',
      ),
      preamble:
          '// Copyright (c) 2026 TaleTin contributors. LGPL-3.0-or-later.\n'
          '// Generated by package:ffigen. Do not edit manually.',
    ),
  ).generate(libclangDylib: args.isEmpty ? null : Uri.file(args.single));
}
