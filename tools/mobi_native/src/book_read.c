void gt_book_free(gt_mobi_book *b) {
    if (!b) return;
    for (uint32_t i = 0; i < b->entry_count; i++) {
        GTEntry *e = &b->entries[i];
        free(e->spans);
        free(e->literal);
        for (uint32_t j = 0; j < e->anchor_count; j++) free(e->anchors[j].value);
        for (uint32_t j = 0; j < e->patch_count; j++) free(e->patches[j].data);
        free(e->anchors);
        free(e->patches);
    }
    for (int i = 0; i < 8; i++) free(b->decoded[i].data);
    /* Resource metadata owns no data except the OPF/NCX generated by libmobi. */
    mobi_free_rawml(b->raw);
    free(b->entries);
    free(b->text_starts);
    free(b);
}

int gt_mobi_scan(gt_mobi_session *s, uint32_t count) {
    if (!s) return 1;
    if (!s->book) {
        s->book = calloc(1, sizeof(*s->book));
        if (!s->book) return 5;
        s->book->session = s;
        s->book->text_starts = calloc(s->text_count + 1, sizeof(uint32_t));
        if (!s->book->text_starts) return 5;
    }
    gt_mobi_book *b = s->book;
    while (count-- && b->scanned < s->text_count) {
        uint32_t i = b->scanned;
        int status = gt_mobi_record(s, (uint32_t)s->first_text + i, 1);
        if (status) return status;
        if (s->result_size > 1024 * 1024 * 1024 - b->text_starts[i]) return 4;
        b->text_starts[i + 1] = b->text_starts[i] + (uint32_t)s->result_size;
        b->scanned++;
    }
    return 0;
}

int gt_text_into(gt_mobi_book *b, uint32_t at, uint32_t length, unsigned char *out) {
    gt_mobi_session *s = b->session;
    if (b->scanned != s->text_count || at > b->text_starts[b->scanned] ||
        length > b->text_starts[b->scanned] - at) return 1;
    uint32_t lo = 0, hi = b->scanned;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        if (b->text_starts[mid + 1] <= at) lo = mid + 1;
        else hi = mid;
    }
    while (length) {
        if (lo >= b->scanned) return 1;
        GTDecoded *cached = NULL;
        for (int i = 0; i < 8; i++) {
            if (b->decoded[i].data && b->decoded[i].record == lo) cached = &b->decoded[i];
        }
        if (!cached) {
            int status = gt_mobi_record(s, (uint32_t)s->first_text + lo, 1);
            if (status) return status;
            if (s->result_size != b->text_starts[lo + 1] - b->text_starts[lo]) return 1;
            cached = &b->decoded[b->cache_cursor++ % 8];
            free(cached->data);
            cached->data = malloc(s->result_size ? s->result_size : 1);
            if (!cached->data) return 5;
            cached->size = (uint32_t)s->result_size;
            cached->record = lo;
            memcpy(cached->data, s->result, s->result_size);
        }
        uint32_t offset = at - b->text_starts[lo];
        uint32_t take = cached->size - offset;
        if (take > length) take = length;
        memcpy(out, cached->data + offset, take);
        at += take; length -= take; out += take; lo++;
    }
    return 0;
}

int gt_entry_into(gt_mobi_book *b, const GTEntry *e, uint32_t at, uint32_t length, unsigned char *out) {
    if (at > e->meta->size || length > e->meta->size - at) return 1;
    uint32_t position = 0;
    for (uint32_t i = 0; i < e->span_count && length; i++) {
        GTSpan span = e->spans[i];
        if (position + span.length > at) {
            uint32_t offset = at - position;
            uint32_t take = span.length - offset;
            if (take > length) take = length;
            int status = gt_text_into(b, span.offset + offset, take, out);
            if (status) return status;
            at += take; length -= take; out += take;
        }
        position += span.length;
    }
    return length ? 1 : 0;
}

int gt_mobi_structure(gt_mobi_session *s) {
    return s && s->book && s->book->scanned == s->text_count
        ? gt_book_structure(s->book) : 1;
}

uint32_t gt_mobi_entries(gt_mobi_session *s) { return s && s->book ? s->book->entry_count : 0; }
int gt_mobi_anchors(gt_mobi_session *s, uint32_t entry) {
    return s && s->book && entry < s->book->entry_count
        ? gt_entry_anchors(s->book, &s->book->entries[entry]) : 1;
}
int gt_mobi_links(gt_mobi_session *s, uint32_t entry) {
    return s && s->book && entry < s->book->entry_count
        ? gt_entry_patch(s->book, &s->book->entries[entry]) : 1;
}

int gt_mobi_metadata(gt_mobi_session *s) {
    if (!s || !s->book || !s->book->raw) return 1;
    gt_mobi_book *b = s->book;
    if (mobi_build_opf(b->raw, s->m) != MOBI_SUCCESS) return 1;
    for (MOBIPart *p = b->raw->resources; p; p = p->next) {
        if (p->type != T_OPF && p->type != T_NCX) continue;
        if (b->entry_count >= 20000) return 4;
        GTEntry *e = &b->entries[b->entry_count++];
        e->kind = 3; e->meta = p; e->output_size = (uint32_t)p->size;
        if (p->type == T_OPF) strcpy(e->name, "content.opf");
        else snprintf(e->name, sizeof(e->name), "resource%05zu.ncx", p->uid);
    }
    return 0;
}

int gt_mobi_entry_info(gt_mobi_session *s, uint32_t number) {
    if (!s || !s->book || number >= s->book->entry_count) return 1;
    GTEntry *e = &s->book->entries[number];
    char info[256];
    /* Numeric ids and fixed extensions are the only source of entry names. */
    int length = snprintf(info, sizeof(info), "%s\n%u\n%d\n%u", e->name,
        e->output_size, e->kind, (unsigned)e->meta->type);
    unsigned char *out = malloc((size_t)length);
    if (!out) return 5;
    memcpy(out, info, (size_t)length);
    free(s->result); s->result = out; s->result_size = (size_t)length;
    return 0;
}

static int gt_copy_piece(gt_mobi_book *b, GTEntry *e, uint32_t at, uint32_t length,
                         const unsigned char *literal, uint32_t piece_length,
                         uint32_t raw_at, uint32_t *position, unsigned char **out,
                         uint32_t *remaining) {
    uint32_t start = *position, end = start + piece_length;
    *position = end;
    if (!*remaining || end <= at || start >= at + length) return 0;
    uint32_t offset = at > start ? at - start : 0;
    uint32_t take = piece_length - offset;
    if (take > *remaining) take = *remaining;
    int status = 0;
    if (literal) memcpy(*out, literal + offset, take);
    else status = gt_entry_into(b, e, raw_at + offset, take, *out);
    *out += take; *remaining -= take;
    return status;
}

int gt_mobi_entry_read(gt_mobi_session *s, uint32_t number, uint32_t at, uint32_t length, int patched) {
    if (!s || !s->book || number >= s->book->entry_count || length > 50 * 1024 * 1024) return 1;
    gt_mobi_book *b = s->book;
    GTEntry *e = &b->entries[number];
    uint32_t size = patched ? e->output_size : (uint32_t)e->meta->size;
    if (at > size || length > size - at) return 1;
    if (e->kind == 2) {
        int status = gt_mobi_record(s, (uint32_t)s->resource_first + (uint32_t)e->meta->uid, 2);
        if (status) return status;
        if (s->result_size != size) return 1;
        memmove(s->result, s->result + at, length);
        s->result_size = length;
        return 0;
    }
    unsigned char *result = malloc(length ? length : 1);
    if (!result) return 5;
    int status = 0;
    if (e->kind == 3) memcpy(result, e->meta->data + at, length);
    else if (!patched || !e->patch_count) status = gt_entry_into(b, e, at, length, result);
    else {
        uint32_t raw_at = 0, position = 0, remaining = length;
        unsigned char *out = result;
        // A late chapter must not walk every earlier anchor/link replacement.
        // Sorted output ends locate the preceding recipe in logarithmic time.
        uint32_t lo = 0, hi = e->patch_count;
        while (lo < hi) {
            uint32_t mid = lo + (hi - lo) / 2;
            if (e->patches[mid].output_end <= at) lo = mid + 1;
            else hi = mid;
        }
        if (lo) {
            GTPatch *previous = &e->patches[lo - 1];
            raw_at = previous->offset + previous->removed;
            position = previous->output_end;
        }
        for (uint32_t i = lo; i < e->patch_count && remaining; i++) {
            GTPatch *p = &e->patches[i];
            status = gt_copy_piece(b, e, at, length, NULL, p->offset - raw_at, raw_at, &position, &out, &remaining);
            if (!status) status = gt_copy_piece(b, e, at, length, p->data, p->length, 0, &position, &out, &remaining);
            if (status) break;
            raw_at = p->offset + p->removed;
        }
        if (!status && remaining) status = gt_copy_piece(b, e, at, length, NULL,
            (uint32_t)e->meta->size - raw_at, raw_at, &position, &out, &remaining);
        if (remaining) status = 1;
    }
    if (status) { free(result); return status; }
    free(s->result); s->result = result; s->result_size = length;
    return 0;
}
