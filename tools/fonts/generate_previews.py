"""Generate name-only font previews. Run after changing built-in fonts or names.

Requires fonttools and PyYAML. --check validates without writing any files.
The complete fonts remain unchanged and are still used for reading.
"""

import argparse
import io
from pathlib import Path
import re

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
import yaml

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "assets/fonts/preview"
BEGIN = "    # BEGIN GENERATED FONT PREVIEWS"
END = "    # END GENERATED FONT PREVIEWS"


def glyph_shapes(font, characters):
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    result = {}
    for character in characters:
        pen = DecomposingRecordingPen(glyphs)
        glyphs[cmap[character]].draw(pen)
        result[character] = (pen.value, font["hmtx"][cmap[character]])
    return result


def generate(check=False):
    catalog = (ROOT / "lib/platform/channels/preset_fonts.dart").read_text("utf-8")
    # The existing Dart directory is the authority for names; do not maintain
    # another hand-written name list or infer names from font filenames.
    names = {}
    for family, body in re.findall(r"'(gt-preset-[^']+)':\s*\((.*?)\),", catalog, re.S):
        names[family] = re.search(r"name:\s*'([^']+)'", body).group(1) + "（内置）"
    manifest_path = ROOT / "pubspec.yaml"
    manifest = manifest_path.read_text("utf-8")
    families = [item for item in yaml.safe_load(manifest)["flutter"]["fonts"]
                if item["family"].startswith("gt-preset-")]
    if set(names) != {item["family"] for item in families}:
        raise ValueError("preset_fonts.dart and pubspec.yaml font families differ")

    generated = {}
    registration = [BEGIN, "    # Name previews only; full fonts above remain unchanged."]
    full_size = 0
    for item in families:
        family = item["family"]
        preview_family = family.replace("gt-preset-", "gt-preview-", 1)
        registration += [f"    - family: {preview_family}", "      fonts:"]
        for face in item["fonts"]:
            source = ROOT / face["asset"]
            weight = face["weight"]
            target = OUTPUT / f"{preview_family}-{weight}.ttf"
            options = subset.Options()
            options.recalc_timestamp = False
            options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
            options.name_languages = ["*"]
            font = subset.load_font(str(source), options)
            characters = {ord(char) for char in names[family] + " …"}
            supported = characters & font.getBestCmap().keys()
            original_shapes = glyph_shapes(font, supported)
            cutter = subset.Subsetter(options=options)
            cutter.populate(unicodes=characters)
            cutter.subset(font)
            if not supported <= font.getBestCmap().keys():
                raise ValueError(f"Preview lost name glyphs: {family}")
            if glyph_shapes(font, supported) != original_shapes:
                raise ValueError(f"Preview changed glyph shapes or spacing: {family}")
            # Rename the derived fonts, retaining copyright/license metadata.
            style = "Bold" if weight == 700 else "Regular"
            for record in font["name"].names:
                if record.nameID in [1, 2, 3, 4, 6, 16, 17]:
                    value = style if record.nameID in [2, 17] else f"{preview_family}-{style}"
                    record.string = value.encode(record.getEncoding())
            buffer = io.BytesIO()
            subset.save_font(font, buffer, options)
            font.close()
            generated[target] = buffer.getvalue()
            full_size += source.stat().st_size
            registration += [f"        - asset: {target.relative_to(ROOT).as_posix()}",
                             f"          weight: {weight}"]
    registration.append(END)
    block = "\n".join(registration)
    updated = (re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, manifest, flags=re.S)
               if BEGIN in manifest else manifest.replace("  fonts:\n", "  fonts:\n" + block + "\n", 1))
    dart_path = ROOT / "lib/platform/channels/preset_font_previews.dart"
    dart = "// Generated by tools/fonts/generate_previews.py; do not edit.\n"
    dart += "const presetFontPreviewNames = <String, String>{\n"
    dart += "".join(f"  '{family}': '{name}',\n" for family, name in names.items())
    dart += "};\n"
    stale = set(OUTPUT.glob("gt-preview-*.ttf")) - generated.keys()
    mismatches = [str(path.relative_to(ROOT)) for path, data in generated.items()
                  if not path.exists() or path.read_bytes() != data]
    if check:
        if stale or mismatches or updated != manifest or not dart_path.exists() or dart_path.read_text("utf-8") != dart:
            raise ValueError("Previews are outdated; run python tools/fonts/generate_previews.py")
    else:
        OUTPUT.mkdir(parents=True, exist_ok=True)
        if OUTPUT.resolve() != OUTPUT.absolute():
            raise ValueError("Preview output must not be a linked directory")
        for path, data in generated.items():
            path.write_bytes(data)
        for path in stale:
            path.unlink()  # Only generated TTF files in this fixed output directory.
        manifest_path.write_text(updated, "utf-8")
        dart_path.write_text(dart, "utf-8")
    preview_size = sum(map(len, generated.values()))
    print(f"{'Checked' if check else 'Generated'} {len(families)} families / {len(generated)} faces: "
          f"{full_size:,} full bytes -> {preview_size:,} preview bytes; removed {len(stale)} stale files")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
