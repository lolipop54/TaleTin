/// 按 CSS 属性名查定义（含别名）。
pub fn property_by_name(name: &str) -> Option<&'static StylePropertyDef> {
    if let Some(target) = alias_target(name) {
        return STYLE_PROPERTIES.iter().find(|p| p.name == target);
    }
    STYLE_PROPERTIES.iter().find(|p| p.name == name)
}

/// 别名指向的标准属性名；不是别名时返回 None。
pub fn alias_target(name: &str) -> Option<&'static str> {
    STYLE_ALIASES
        .iter()
        .find(|(alias, _)| *alias == name)
        .map(|(_, target)| *target)
}

/// 某个标签的默认声明；没登记过返回空切片。
pub fn tag_defaults(tag: &str) -> &'static [TagDefaultDecl] {
    TAG_DEFAULTS
        .iter()
        .find(|entry| entry.tag == tag)
        .map(|entry| entry.declarations)
        .unwrap_or(&[])
}
