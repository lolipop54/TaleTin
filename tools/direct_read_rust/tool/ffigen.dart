import 'dart:io';
import 'package:ffigen/ffigen.dart';

void main(List<String> args) {
  final root = Platform.script.resolve('../');
  final header = root.resolve('src/scan.h');
  FfiGenerator(
    headers: Headers(entryPoints: [header], include: (path) => path == header),
    functions: Functions(
      include: (decl) => decl.originalName.startsWith('gt_'),
      // ffigen 20.1.1 尚无 recordUse API；当前 Code Assets 保留整库。
    ),
    structs: Structs.includeSet({'GtScanResult'}),
    output: Output(
      dartFile: root.resolve('lib/src/third_party/scan.g.dart'),
      style: const NativeExternalBindings(
        assetId: 'package:direct_read_rust/reader_native',
      ),
      preamble:
          '// Copyright (c) 2026 GT Reader contributors. MIT license, see LICENSE.\n'
          '// Generated by package:ffigen. Do not edit manually.',
    ),
  ).generate(libclangDylib: args.isEmpty ? null : Uri.file(args.single));
}
