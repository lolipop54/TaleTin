/// 字体名解析：问平台「这个字体族实际用的是哪个字体」。
///
/// 面板上的「系统 / 宋体 / 楷体」是**请求**，设备上不一定装了；
/// 拿系统实际使用的字体名显示出来，读者才知道当前正文到底是哪个字形，
/// 而不是界面说宋体、实际回退到了默认字体。
/// 平台不支持（测试、桌面端）时返回空表，界面就不显示这一行。
library;

abstract interface class FontResolver {
  /// 入参是请求的字体族名（空串表示系统默认），返回 请求 → 实际字体名。
  /// 值可能为 null，表示系统里没有这个族（回退到默认字体）。
  Future<Map<String, String?>> resolve(List<String> families);
}
